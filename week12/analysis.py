# 정제(df)는 프롬프트 A, 필터링·그룹화는 B·C, 반별평균(df)는 D에 대한 AI 응답을 그대로 옮겼다.
# 받은 코드는 고치지 않았고, AI가 안내한 대로 사용 예시만 if __name__ == "__main__": 안에 넣었다.
import pandas as pd


def 정제(df):
    # 원본을 건드리지 않도록 복사본을 만든다
    결과 = df.copy()
    print("시작:", len(결과), "행")

    # 1) 점수가 비어 있는 행을 삭제한다
    결과 = 결과.dropna(subset=["점수"])
    print("1) 빈 점수 삭제 후:", len(결과), "행")

    # 2) 모든 열이 완전히 같은 중복 행은 하나만 남긴다
    결과 = 결과.drop_duplicates()
    print("2) 중복 삭제 후:", len(결과), "행")

    # 3) 반과 과목 값의 앞뒤 공백을 제거한다
    결과["반"] = 결과["반"].str.strip()
    결과["과목"] = 결과["과목"].str.strip()
    print("3) 공백 제거 후:", len(결과), "행")

    # 4) 점수가 0 이상 100 이하인 행만 남긴다
    결과 = 결과[(결과["점수"] >= 0) & (결과["점수"] <= 100)]
    print("4) 범위 밖 점수 삭제 후:", len(결과), "행")

    # 빈 값 때문에 실수형이 된 점수를 정수형으로 되돌린다
    결과["점수"] = 결과["점수"].astype(int)

    # 행 번호를 0부터 다시 매긴다
    결과 = 결과.reset_index(drop=True)
    return 결과


def 반별평균(df):
    # 반으로 묶어 개수·평균·중앙값·최댓값을 한 표로 만든다
    표 = df.groupby("반")["점수"].agg(["count", "mean", "median", "max"])

    # 소수 둘째 자리까지 반올림한다
    표 = 표.round(2)

    # 표를 출력한다
    print(표)

    # 반 이름을 키로 하는 평균값 Series를 반환한다
    return 표["mean"]


# 이 파일을 직접 실행할 때만 아래 코드를 실행한다
if __name__ == "__main__":
    df = pd.read_csv("scores_2026.csv", encoding="utf-8", dtype={"학번": str})
    깨끗한_df = 정제(df)
    print(깨끗한_df.head())

    # ① 필터링: 과목이 '수학'인 행만 남긴다
    수학_df = 깨끗한_df[깨끗한_df["과목"] == "수학"]
    print("수학 행 수:", len(수학_df))

    # (응용) 1반이면서 90점 이상인 행만 남긴다
    우수_1반_df = 깨끗한_df[(깨끗한_df["반"] == "1반") & (깨끗한_df["점수"] >= 90)]
    print("1반 90점 이상 행 수:", len(우수_1반_df))

    # ② 그룹화: 반별 점수 평균을 구한다
    반별_평균 = 깨끗한_df.groupby("반")["점수"].mean()
    print(반별_평균)

    # 과목과 반 두 기준으로 묶어 점수 평균을 구한다
    과목_반별_평균 = 깨끗한_df.groupby(["과목", "반"])["점수"].mean()
    print(과목_반별_평균)

    # ③ 통계: 반별 개수·평균·중앙값·최댓값
    평균 = 반별평균(깨끗한_df)
    print(평균)
    print(평균["1반"])
